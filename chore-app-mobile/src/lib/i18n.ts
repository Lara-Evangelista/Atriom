const deviceLanguage = getLocales()[0]?.languageCode === 'pt' ? 'pt-PT' : 'en';

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: deviceLanguage,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false, 
    },
    react: {
      useSuspense: false
    }
  });

// A manually-picked language (set in You \u2192 Personal Settings) overrides the
// device locale once it loads. This is a per-device preference, so it's kept
// in AsyncStorage rather than synced to the backend.
AsyncStorage.getItem(UI_LANGUAGE_STORAGE_KEY)
  .then((stored) => {
    if (stored && stored !== i18n.language) i18n.changeLanguage(stored);
  })
  .catch(() => {});

export async function setUiLanguage(lang: 'en' | 'pt-PT') {
  await i18n.changeLanguage(lang);
  await AsyncStorage.setItem(UI_LANGUAGE_STORAGE_KEY, lang);
}

